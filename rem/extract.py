"""Scan Claude Code and Codex transcripts for candidate friction events.

Mechanical only: detect corrections, permission denials, tool errors, heavy
human-in-the-loop, and learnings via heuristics, then bucket them per
(session, day, kind). The LLM step downstream assigns axis/valence/signature
and clusters them into recurring patterns.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import signal
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

from . import config
from .db import ConsolidationDB

# A user turn that pushes back on what the agent just did.
CORRECTION_RE = re.compile(
    r"\b(no,|nope|that'?s? (wrong|not right|not what)|incorrect|undo|revert|"
    r"roll ?back|don'?t |do not |stop |actually,? |instead|not like that|"
    r"never ?mind|scratch that|go back|not what i (wanted|asked|meant)|"
    r"why did you|you (shouldn'?t|were supposed)|i said)",
    # No trailing \b: several alternatives end in punctuation/space (e.g. "no,",
    # "actually, "), where a trailing word-boundary would never match.
    re.IGNORECASE,
)

# A turn where the human or agent captures something worth keeping (a lift).
LEARNING_RE = re.compile(
    r"\b(got it|i see|makes sense|the pattern is|use .{1,40} instead of|"
    r"turns out|now i (understand|get it)|good to know|the (trick|key) is|"
    r"lesson|note for next time|remember (to|that))\b",
    re.IGNORECASE,
)

# A tool result / system line that reads as the human refusing an action.
DENIAL_RE = re.compile(
    r"(user (doesn'?t|did not|didn'?t) want|user (rejected|declined|denied)|"
    r"permission (denied|to use)|not allow|operation (was )?(rejected|cancell?ed)|"
    r"requested permission|blocked by hook)",
    re.IGNORECASE,
)

# An agent stopped specifically to obtain a human verdict. Keep this separate
# from a refusal: Codex hooks explicitly describe these as approval requests,
# and collapsing the two hides avoidable HITL churn behind "the user denied".
APPROVAL_RE = re.compile(
    r"(human approval required|requires? (human )?approval|approval required|"
    r"ask .{0,80} explicit yes|request(?:ed|ing)? (?:user )?approval|"
    r"escalated permissions?|sandbox_permissions.{0,40}require_escalated)",
    re.IGNORECASE,
)

# Sessions started by the cron harness — skip so the agent doesn't eat its tail.
HEADLESS_MARKER = "[AUTOMATED HEADLESS RUN]"

# Injected machine text arrives inside "user" records but isn't the user's words:
# slash/local-command scaffolding, hook output, task notifications, reminders.
# Strip these blocks, THEN check what genuine human text remains — so a real
# "no, revert that" with an appended <system-reminder> still counts, while a
# pure task-notification turn doesn't. (The agent flagged this noise itself.)
MACHINE_BLOCK_RE = re.compile(
    r"<(system-reminder|task-notification|local-command-stdout|local-command-caveat|"
    r"command-name|command-message|command-args|bash-input|bash-stdout|bash-stderr|"
    r"auto-task|subagent_notification|task)>.*?</\1>",
    re.DOTALL | re.IGNORECASE,
)
# If any of these survive the block-strip, the whole turn is injected context.
WHOLE_TURN_MARKERS = (
    "this session is being continued from a previous",
    "sessionstart hook",
    "the following deferred tools are now available",
    "messages below were generated by the user while running local commands",
    "codebase and user instructions are shown below",
    "# agents.md instructions",
    "<environment_context>",
    "<codex_internal_context",
    # Driver prompts for unattended runs: shim/Workflow ticks that arrive as
    # "user" turns but are a script talking, not the user. They carry no
    # [AUTOMATED HEADLESS RUN] banner, so match their own preambles.
    "you are driving one unattended",
    "resume this lane's in-flight",
    "do exactly these steps, nothing else",
    "(scheduled, act autonomously",
)

# A loaded skill's body is injected into the turn with this header and runs to
# the end of the text block. Strip it (rather than dropping the whole turn) so a
# genuine correction that merely preceded a skill load still counts.
SKILL_PREAMBLE_RE = re.compile(
    r"Base directory for this skill:.*", re.DOTALL | re.IGNORECASE
)


# Text that is ABOUT the consolidation, not friction to learn from: a pasted or
# read briefing/ledger, or this package's own source (whose regex literals match
# the very trigger words above). Scanning it mints phantom corrections/denials -
# caught while dogfooding REM on its own sessions. Skip it like a machine block.
SELF_REFERENTIAL_MARKERS = (
    "night consolidation —",         # a briefing header
    "<!--p:",                        # journal proposal / pattern marker
    "standing patterns (open",       # ledger
    "decisions logged:",             # ledger
    "cron_result {",                 # cron final line
    "correction_re", "denial_re", "learning_re",   # this package's own source
    "emit candidate friction events",              # extract.py docstring
)


def _is_self_referential(text: str) -> bool:
    """True if the text is a consolidation artifact or this package's own source."""
    low = text.lower()
    return any(m in low for m in SELF_REFERENTIAL_MARKERS)


def _clean_user_text(joined: str) -> str:
    """Return the human-authored remainder of a user turn, or '' if it's pure
    injected machine text (or text about the consolidation itself)."""
    cleaned = MACHINE_BLOCK_RE.sub(" ", joined)
    cleaned = SKILL_PREAMBLE_RE.sub(" ", cleaned)
    low = cleaned.lower()
    if any(m in low for m in WHOLE_TURN_MARKERS) or _is_self_referential(cleaned):
        return ""
    return cleaned.strip()

MAX_EVIDENCE = 3
EVIDENCE_CHARS = 240


def _texts(content) -> list[str]:
    if isinstance(content, str):
        return [content] if content.strip() else []
    out: list[str] = []
    if isinstance(content, list):
        for b in content:
            if not isinstance(b, dict):
                continue
            text = b.get("text") or b.get("input_text") or b.get("output_text")
            if b.get("type") in ("text", "input_text", "output_text") and text:
                out.append(text)
    return out


def _output_text(output) -> str:
    """Flatten either agent's tool-output envelope to searchable text."""
    texts = _texts(output)
    if texts:
        return "\n".join(texts)
    if isinstance(output, dict):
        return json.dumps(output, sort_keys=True)
    return output if isinstance(output, str) else ""


def _tool_failed(text: str) -> bool:
    """Recognize wrapper failures, including nonzero exit codes in JSON output."""
    return bool(
        re.search(r"^Script failed\b", text, re.IGNORECASE)
        or re.search(r"Process exited with code [1-9]\d*", text, re.IGNORECASE)
        or re.search(r"[\"']exit_code[\"']\s*[:=]\s*[1-9]\d*", text)
    )


CMD_IN_EXEC_RE = re.compile(r'\bcmd\s*:\s*"((?:[^"\\]|\\.)*)"')
CHUNK_START_RE = re.compile(r'\{"i":(\d+),')
CHUNK_EXIT_RE = re.compile(r'"exit_code"\s*:\s*(\d+)')
# exit 1 from a search or a comparison means "nothing matched", not a failure
NO_MATCH_PROGRAMS = {"rg", "grep", "test", "[", "diff", "cmp"}


def _exec_chunks(text: str) -> list[tuple[int, int, str]]:
    """A batched Codex exec cell prints one {"i":N,...,"exit_code":K,...} result per command.
    Returns (index, exit_code, chunk text) for each. Flagging the whole batch on any nonzero code
    quoted its first command, which had usually passed."""
    starts = [m.start() for m in CHUNK_START_RE.finditer(text)]
    chunks = []
    for a, b in zip(starts, starts[1:] + [len(text)]):
        seg = text[a:b]
        code = CHUNK_EXIT_RE.search(seg)
        if code:
            chunks.append((int(CHUNK_START_RE.match(seg).group(1)), int(code.group(1)), seg))
    return chunks


def _failing_chunk(text: str, call) -> tuple[str, str] | None:
    """(program label, chunk text) of the first command in a batch that really failed. The command
    for chunk i is the cell's i-th exec_command; a no-match exit 1 from rg/grep/test is not a fail.
    ponytail: the last program of a chained command stands for its exit code."""
    args = call[1] if call else None
    cmds = CMD_IN_EXEC_RE.findall(args) if isinstance(args, str) else []
    for i, code, seg in _exec_chunks(text):
        if not code:
            continue
        label = _command_programs(cmds[i]) if i < len(cmds) else ""
        if code == 1 and label.split("+")[-1] in NO_MATCH_PROGRAMS:
            continue
        return label, seg
    return None
ENV_ASSIGN_RE = re.compile(r"^[A-Za-z_]\w*=")
SEGMENT_RE = re.compile(r"&&|\|\||;|\n")
SUBST_RE = re.compile(r"\$\([^()]*\)|`[^`]*`")
LEAD_WORDS = {"do", "then", "else", "time", "env", "sudo", "nohup", "!", "{", "(", "rtk", "proxy"}
SKIP_PROGRAMS = {"cd", "for", "while", "until", "if", "case", "done", "fi", "esac", "export", "set",
                "echo", "printf"}


def _command_programs(command: str) -> str:
    """Every program a shell command chains, joined with +: the exit code belongs to one of
    them, and a chain's first program is often not it."""
    heads = []
    for segment in SEGMENT_RE.split(SUBST_RE.sub("_", command)):
        tokens = segment.split()
        while tokens and (ENV_ASSIGN_RE.match(tokens[0]) or tokens[0] in LEAD_WORDS):
            tokens.pop(0)
        if tokens and tokens[0] not in SKIP_PROGRAMS:
            heads.append(Path(tokens[0].strip("'\"()")).name)
    return "+".join(dict.fromkeys(heads))


def _call_label(name: str | None, args) -> str:
    """What a tool call ran: the shell program for shell calls, else the tool name.
    A bare "Exit code 1" can't be routed to a fix without it."""
    if isinstance(args, str):
        # Codex exec cells often batch several calls in one Promise.allSettled
        cmds = CMD_IN_EXEC_RE.findall(args)
        if cmds:
            args = {"cmd": "; ".join(cmds)}
        else:
            try:
                args = json.loads(args)
            except json.JSONDecodeError:
                args = None
    command = (args.get("command") or args.get("cmd")) if isinstance(args, dict) else None
    if isinstance(command, list):
        command = " ".join(map(str, command[2:] if command[1:2] in (["-c"], ["-lc"]) else command))
    head = _command_programs(command) if isinstance(command, str) else ""
    return head or name or ""


def _local_date(ts: str) -> str | None:
    if not ts:
        return None
    try:
        dt = datetime.fromisoformat(ts.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        return dt.astimezone().date().isoformat()
    except ValueError:
        return None


def _project_from_cwd(cwd: str | None) -> str:
    if not cwd:
        return "unknown"
    name = Path(cwd).name
    return "home" if name == Path.home().name else name


# Keys pasted into a chat stay in the transcript; evidence quotes land in SQLite, the briefing and
# any published copy of it.
SECRET_RE = re.compile(
    r"(sk-(?:or-v1-|ant-|proj-)?[A-Za-z0-9_\-]{16,}|gh[pousr]_[A-Za-z0-9]{20,}|xox[abprs]-[A-Za-z0-9\-]{10,}"
    r"|AKIA[0-9A-Z]{16}|AIza[0-9A-Za-z_\-]{30,}|\d{8,10}:[A-Za-z0-9_\-]{30,}"
    r"|(?:api[_-]?key|token|secret|password)\s*[=:]\s*\S{12,})", re.I)


def redact(text: str) -> str:
    """Shared transcript/retro redaction without discarding the item text."""
    return SECRET_RE.sub("[REDACTED]", " ".join(text.split()))


def _trim(text: str) -> str:
    return redact(text)[:EVIDENCE_CHARS]


class Signal:
    __slots__ = ("kind", "day", "quotes", "count")

    def __init__(self, kind: str, day: str):
        self.kind = kind
        self.day = day
        self.quotes: list[str] = []
        self.count = 0

    def add(self, quote: str) -> None:
        self.count += 1
        if len(self.quotes) < MAX_EVIDENCE and quote:
            self.quotes.append(_trim(quote))


BENCH_DIR_RE = re.compile(r"-scratchpad-(bench-ws-|denytest$)")


def scan_file(path: Path, lo: str, hi: str) -> dict:
    """Parse one transcript. Return per-(day, kind) Signals within [lo, hi],
    plus session metadata and human-in-the-loop counters."""
    session_id = path.stem
    agent = "claude"
    project = "unknown"
    git_branch = None
    signals: dict[tuple[str, str], Signal] = {}
    n_user = n_tooluse = 0
    # bench runs replay real prompts and denytest runs are probes: neither is real friction
    headless = bool(BENCH_DIR_RE.search(path.parent.name))
    started: str | None = None

    def sig(kind: str, day: str) -> Signal:
        key = (kind, day)
        if key not in signals:
            signals[key] = Signal(kind, day)
        return signals[key]

    def record_human(joined: str, day: str | None) -> None:
        nonlocal n_user, headless
        if HEADLESS_MARKER in joined:
            headless = True
        human = _clean_user_text(joined)
        if not human:
            return
        n_user += 1
        if not day or not (lo <= day <= hi):
            return
        if APPROVAL_RE.search(human):
            sig("approval", day).add(human)
        elif DENIAL_RE.search(human):
            sig("denial", day).add(human)
        if CORRECTION_RE.search(human):
            sig("correction", day).add(human)
        if LEARNING_RE.search(human):
            sig("learning", day).add(human)

    def record_tool_result(text: str, day: str | None, *, failed: bool, call=None,
                           label: str | None = None) -> None:
        # a successful result can carry "denied" as data (a grep hit, a log line)
        if not failed or not text or _is_self_referential(text) or not day or not (lo <= day <= hi):
            return
        if APPROVAL_RE.search(text):
            sig("approval", day).add(text)
        elif DENIAL_RE.search(text):
            sig("denial", day).add(text)
        else:
            if label is None:
                label = _call_label(*call) if call else ""
            sig("error", day).add(f"[{label}] {text}" if label else text)

    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return {}

    codex_meta_seen = False
    calls: dict[str, tuple] = {}
    for raw in lines:
        raw = raw.strip()
        if not raw:
            continue
        try:
            rec = json.loads(raw)
        except json.JSONDecodeError:
            continue
        if not isinstance(rec, dict):
            continue

        rtype = rec.get("type")
        payload_value = rec.get("payload")
        if payload_value is None:
            payload = {}
        elif isinstance(payload_value, dict):
            payload = payload_value
        elif rtype in {"session_meta", "turn_context", "event_msg", "response_item"}:
            continue
        else:
            payload = {}
        if rtype == "session_meta":
            agent = "codex"
            if not codex_meta_seen:
                codex_meta_seen = True
                session_id = payload.get("id") or payload.get("session_id") or session_id
                source = payload.get("source")
                if isinstance(source, dict) and source.get("subagent"):
                    headless = True
                if payload.get("cwd"):
                    project = _project_from_cwd(payload["cwd"])
            continue
        if rtype == "turn_context":
            agent = "codex"
            if payload.get("cwd"):
                project = _project_from_cwd(payload["cwd"])
            continue
        if rec.get("cwd"):
            project = _project_from_cwd(rec["cwd"])
        if rec.get("gitBranch"):
            git_branch = rec["gitBranch"]

        day = _local_date(rec.get("timestamp", ""))
        if day and (started is None or day < started):
            started = day
        msg = rec.get("message") or {}
        content = msg.get("content")

        if rtype == "event_msg":
            agent = "codex"
            if payload.get("type") == "user_message":
                record_human(payload.get("message") or payload.get("text") or "", day)

        elif rtype == "user":
            texts = _texts(content)
            joined = "\n".join(texts)
            # tool_result blocks (denials / errors arrive here)
            if isinstance(content, list):
                for b in content:
                    if isinstance(b, dict) and b.get("type") == "tool_result":
                        body = b.get("content")
                        btext = _output_text(body)
                        record_tool_result(btext, day, failed=bool(b.get("is_error")),
                                           call=calls.get(b.get("tool_use_id")))
            # genuine human turns only. isMeta marks harness-injected turns (slash-command
            # bodies, messages relayed from other sessions)
            if not rec.get("isMeta"):
                record_human(joined, day)

        elif rtype == "assistant":
            if isinstance(content, list):
                for b in content:
                    if isinstance(b, dict) and b.get("type") == "tool_use":
                        n_tooluse += 1
                        calls[b.get("id")] = (b.get("name"), b.get("input"))
            for t in _texts(content):
                if (day and lo <= day <= hi and not _is_self_referential(t)
                        and LEARNING_RE.search(t)):
                    sig("learning", day).add(t)

        elif rtype == "response_item":
            agent = "codex"
            ptype = payload.get("type")
            if ptype == "message":
                role = payload.get("role")
                joined = "\n".join(_texts(payload.get("content")))
                if role == "user":
                    record_human(joined, day)
                elif role == "assistant":
                    for text in _texts(payload.get("content")):
                        if (day and lo <= day <= hi and not _is_self_referential(text)
                                and LEARNING_RE.search(text)):
                            sig("learning", day).add(text)
            elif ptype in ("custom_tool_call", "function_call"):
                n_tooluse += 1
                calls[payload.get("call_id")] = (
                    payload.get("name"), payload.get("input") or payload.get("arguments"))
            elif ptype in ("custom_tool_call_output", "function_call_output"):
                text = _output_text(payload.get("output"))
                call = calls.get(payload.get("call_id"))
                if _exec_chunks(text):
                    bad = _failing_chunk(text, call)
                    if bad:
                        record_tool_result(bad[1], day, failed=True, label=bad[0] or None, call=call)
                    continue
                failed = _tool_failed(text)
                # A successful grep/read may contain the words "approval" or
                # "denied" as data. Only failed Codex calls are execution signals.
                if failed:
                    record_tool_result(text, day, failed=True,
                                       call=calls.get(payload.get("call_id")))

    return {
        "session_id": session_id,
        "agent": agent,
        "project": project,
        "git_branch": git_branch,
        "signals": signals,
        "n_user": n_user,
        "n_tooluse": n_tooluse,
        "headless": headless,
        "started_date": started,
    }


def _event_id(agent: str, session_id: str, day: str, kind: str) -> str:
    # Preserve the pre-Codex Claude identity so overlapping windows remain idempotent.
    identity = f"{session_id}|{day}|{kind}" if agent == "claude" else \
        f"{agent}|{session_id}|{day}|{kind}"
    return hashlib.sha1(identity.encode()).hexdigest()[:16]


def signals_to_events(scan: dict, run_date: str, today: str,
                      window: int) -> list[dict]:
    """Turn a session scan into candidate event rows (one per day+kind)."""
    if scan.get("headless"):
        return []
    events: list[dict] = []
    KIND_TITLE = {
        "correction": "corrections",
        "approval": "human approval gates",
        "denial": "permission denials / refusals",
        "error": "tool errors",
        "learning": "learnings",
    }
    for (kind, day), s in scan["signals"].items():
        if s.count == 0:
            continue
        days_ago = (date.fromisoformat(today) - date.fromisoformat(day)).days
        weight = config.recency_weight(days_ago, window)
        if weight == 0:
            continue
        detail = (f"{s.count}× in {scan['agent']} session "
                  f"{scan['session_id'][:8]} ({scan['project']})")
        events.append({
            "id": _event_id(scan["agent"], scan["session_id"], day, kind),
            "run_date": run_date,
            "occurred_at": day,
            "occurred_date": day,
            "session_id": scan["session_id"],
            "agent": scan["agent"],
            "project": scan["project"],
            "git_branch": scan["git_branch"],
            "kind": kind,
            "title": f"{KIND_TITLE.get(kind, kind)} ({scan['project']})",
            "detail": detail,
            "evidence": s.quotes,
            "signal_count": s.count,
            "raw_weight": weight,
        })

    # Heavy human-in-the-loop: many corrections + low autonomy in one session.
    corrections = sum(s.count for (k, _), s in scan["signals"].items() if k == "correction")
    if corrections >= 3:
        last_day = max((day for (_, day) in scan["signals"]), default=today)
        days_ago = (date.fromisoformat(today) - date.fromisoformat(last_day)).days
        weight = config.recency_weight(days_ago, window)
        if weight:
            events.append({
                "id": _event_id(scan["agent"], scan["session_id"], last_day, "loop"),
                "run_date": run_date,
                "occurred_at": last_day,
                "occurred_date": last_day,
                "session_id": scan["session_id"],
                "agent": scan["agent"],
                "project": scan["project"],
                "git_branch": scan["git_branch"],
                "kind": "loop",
                "title": f"heavy back-and-forth ({scan['project']})",
                "detail": (f"{corrections} corrections vs {scan['n_tooluse']} tool "
                           f"actions across {scan['n_user']} human turns"),
                "evidence": [],
                "signal_count": corrections,
                "raw_weight": weight,
            })
    return events


def iter_session_files(window: int, today: str):
    cutoff = datetime.fromisoformat(today).replace(tzinfo=timezone.utc) - timedelta(days=window + 1)
    cutoff_ts = cutoff.timestamp()
    seen: set[Path] = set()
    sources = (
        (config.CLAUDE_PROJECTS_DIR, "*/*.jsonl"),
        (config.CODEX_SESSIONS_DIR, "**/*.jsonl"),
        (config.CODEX_ARCHIVE_DIR, "*.jsonl"),
    )
    for root, pattern in sources:
        if not root.exists():
            continue
        for path in root.glob(pattern):
            try:
                resolved = path.resolve()
                if resolved not in seen and path.stat().st_mtime >= cutoff_ts:
                    seen.add(resolved)
                    yield path
            except OSError:
                continue


def run(today: str, window: int, db: ConsolidationDB, dry_run: bool = False,
        backfill: bool = False, run_id: int | None = None) -> dict:
    lo = (date.fromisoformat(today) - timedelta(days=window)).isoformat()
    hi = today
    owned_run = run_id is None
    if not dry_run:
        db.close_stale_runs()
    run_id = None if dry_run else (db.start_run(today) if owned_run else run_id)
    all_events: list[dict] = []
    projects: set[str] = set()
    from . import retro
    imported = retro.collect(db, today, dry_run=dry_run)
    all_events.extend(imported['candidates'])
    projects.update(ev['project'] for ev in imported['candidates'])
    n_sessions = 0
    try:
        for path in iter_session_files(window, today):
            scan = scan_file(path, lo, hi)
            if not scan:
                continue
            n_sessions += 1
            if not dry_run:
                db.upsert_session(scan["agent"], scan["session_id"], scan.get("started_date"),
                                  scan.get("headless", False))
            evs = signals_to_events(scan, today, today, window)
            if evs:
                projects.add(scan["project"])
            for ev in evs:
                all_events.append(ev)
                if not dry_run:
                    db.insert_event(ev)
    except BaseException as e:  # incl. SystemExit from a teardown signal: never leave the row open
        if run_id is not None:
            db.finish_run(run_id, status="failed", sessions_scanned=n_sessions, window_days=window,
                          error=f"{type(e).__name__}: {e}"[:300])
        raise
    if not dry_run:
        db.finish_run(run_id, sessions_scanned=n_sessions,
                      projects=json.dumps(sorted(projects)),
                      events_extracted=len(all_events), window_days=window,
                      status=("backfill" if backfill else "extracted") if owned_run else "running",
                      **({} if owned_run else {"finished_at": None}))
    return {"sessions": n_sessions, "events": len(all_events),
            "projects": sorted(projects), "candidates": all_events, "run_id": run_id}


def _exit_on_signal(signum, _frame) -> None:
    raise SystemExit(128 + signum)


def main() -> None:
    ap = argparse.ArgumentParser(description="Extract candidate friction events.")
    ap.add_argument("--window", type=int, default=config.DEFAULT_WINDOW)
    ap.add_argument("--today", default=date.today().isoformat())
    ap.add_argument("--db", default=None)
    ap.add_argument("--dry-run", action="store_true",
                    help="print candidates as JSON, write nothing")
    ap.add_argument("--backfill", action="store_true",
                    help="fill days REM missed; covers them without counting as a nightly run")
    args = ap.parse_args()

    for sig in (signal.SIGTERM, signal.SIGHUP):  # tmux teardown sends these; let run() close its row
        signal.signal(sig, _exit_on_signal)
    db = ConsolidationDB(Path(args.db) if args.db else None)
    result = run(args.today, args.window, db, dry_run=args.dry_run, backfill=args.backfill)
    if args.dry_run:
        print(json.dumps(result["candidates"], indent=2))
    else:
        print(f"scanned {result['sessions']} sessions across "
              f"{len(result['projects'])} projects -> {result['events']} candidate events")
    db.close()


if __name__ == "__main__":
    main()
