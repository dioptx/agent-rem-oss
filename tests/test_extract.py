TODAY = "2026-06-13"
Y1 = "2026-06-12T10:00:00Z"   # yesterday (local-ish) — within window


def write_session(tmp_path, name, records):
    proj = tmp_path / "-home-example-projects-example-data"
    proj.mkdir(parents=True, exist_ok=True)
    f = proj / f"{name}.jsonl"
    f.write_text("\n".join(json.dumps(r) for r in records), encoding="utf-8")
    return f


def user(text, ts=Y1):
    return {"type": "user", "message": {"role": "user",
            "content": [{"type": "text", "text": text}]},
            "timestamp": ts, "cwd": "/home/example/projects/example-data",
            "gitBranch": "main"}


def tool_result(content, ts=Y1, is_error=False):
    return {"type": "user", "message": {"role": "user", "content": [
            {"type": "tool_result", "is_error": is_error, "content": content}]},
            "timestamp": ts, "cwd": "/home/example/projects/example-data"}


def assistant_tool(name, ts=Y1):
    return {"type": "assistant", "message": {"role": "assistant", "content": [
            {"type": "tool_use", "name": name, "input": {}}]},
            "timestamp": ts, "cwd": "/home/example/projects/example-data"}


def codex_record(rtype, payload, ts=Y1):
    return {"type": rtype, "payload": payload, "timestamp": ts}


def codex_message(role, text, ts=Y1):
    return codex_record("response_item", {
        "type": "message", "role": role,
        "content": [{"type": "input_text", "text": text}],
    }, ts)


