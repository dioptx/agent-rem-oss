def test_bench_sessions_are_headless(tmp_path):
    records = [user("no, wrong"), user("actually, do it differently"), user("revert that")]
    headless = {}
    for name in ("-private-tmp-claude-501-x-scratchpad",
                 "-private-tmp-claude-501-x-scratchpad-bench-ws-real-base",
                 "-private-tmp-claude-501-x-scratchpad-denytest"):
        f = tmp_path / name / "s.jsonl"
        f.parent.mkdir()
        f.write_text("\n".join(json.dumps(r) for r in records), encoding="utf-8")
