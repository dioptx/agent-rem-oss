    assert scan["session_id"] == "codex-session"
    assert scan["project"] == "example-data"
    assert scan["n_user"] == 1
    assert scan["n_tooluse"] == 1
    kinds = {kind for kind, _ in scan["signals"]}
    assert {"approval", "correction"} <= kinds
    events = signals_to_events(scan, TODAY, TODAY, window=5)
    assert all(event["agent"] == "codex" for event in events)


