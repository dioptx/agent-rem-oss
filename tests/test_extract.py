def test_command_programs_skips_env_assignments_and_cd():
    assert extract._command_programs("FOO=1 BAR=x git status") == "git"
    assert extract._command_programs("cd /tmp && /usr/bin/grep -n x y") == "grep"
    assert extract._command_programs("cd /tmp") == ""
    # the exit code of a chain can come from any program in it, so name them all
    assert extract._command_programs("git fetch o b 2>&1 | tail -2; ls -d /x-moves 2>&1") == "git+ls"
    assert extract._command_programs("GH_TOKEN=$(gh auth token --user x) gh pr merge 24") == "gh"
    assert extract._command_programs("for n in 1 2; do gh pr view $n; done") == "gh"


