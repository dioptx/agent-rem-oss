def _batch_scan(tmp_path, cmds, chunk_codes):
    """Scan one batched Codex exec cell whose i-th command exited with chunk_codes[i]."""
    f = tmp_path / "rollout-chunks.jsonl"
    cell = "await Promise.allSettled([" + ", ".join(
        f'tools.exec_command({{cmd:"{c}"}})' for c in cmds) + "])"
    out = "Script completed Wall time 1.0 seconds Output: " + " ".join(
        f'{{"i":{i},"status":"fulfilled","result":{{"chunk_id":"c{i}","exit_code":{code},'
        f'"output":"out-{i}"}}}}' for i, code in enumerate(chunk_codes))
    records = [
        codex_record("session_meta", {"id": "chunk-session", "cwd": "/home/example"}),
        codex_record("response_item", {"type": "custom_tool_call", "name": "exec", "call_id": "c3",
                                        "input": cell}),
        codex_record("response_item", {"type": "custom_tool_call_output", "call_id": "c3",
                                        "output": [{"type": "input_text", "text": out}]}),
    ]
    f.write_text("\n".join(json.dumps(r) for r in records), encoding="utf-8")
    scan = scan_file(f, "2026-06-08", TODAY)
    return [q for (kind, _), s in scan["signals"].items() if kind == "error" for q in s.quotes]


